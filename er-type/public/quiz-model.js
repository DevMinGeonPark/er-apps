      const tip = (index === leadIndex && leaders === 0 ? '이번 판에는 첫 제안 하나만 먼저 꺼내보세요. ' : '')
        + (risk === '0' ? '들어가기 전에 필요한 준비를 한 가지 말해주세요.' : '기회를 제안할 때 빠져나올 조건도 함께 말해주세요.')
        + (adaptability === '0' ? ' 익숙한 계획의 핵심을 동료에게 알려주세요.' : ' 계획이 바뀌면 새 합류 지점을 알려주세요.');
      return { code: member.code, name: member.name, role, tip };
